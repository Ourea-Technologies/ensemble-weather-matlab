"""Generate the toolbox's decoding table from the pinned spec.

The toolbox decodes JSON with MATLAB's ``jsondecode`` and then walks the
result against this table, so every response struct has the same fields in
the same order, each renamed field (BEHAVIOR.md 3.0) carries its SDK name,
timestamps are ``datetime`` values, and absent values are ``[]``.

MATLAB has no YAML reader, so this script (Python, PyYAML) turns
``spec/openapi/v1/openapi.yaml`` and the rename table in ``spec/BEHAVIOR.md``
into two JSON files:

* ``toolbox/+ensembleweather/+internal/schema.json``: objects, enums and
  operations (shipped in the toolbox);
* ``tests/fixtures/spec-examples.json``: every response example in the spec,
  which the drift test decodes.

Usage::

    python3 scripts/gen_schema.py          # rewrite both files
    python3 scripts/gen_schema.py --check  # exit 1 if either is stale

Generated by this script from ensemble-weather-spec; BSD-2-Clause.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
SCHEMA_OUT = ROOT / "toolbox" / "+ensembleweather" / "+internal" / "schema.json"
EXAMPLES_OUT = ROOT / "tests" / "fixtures" / "spec-examples.json"

# MATLAB keywords cannot be struct field names; such a wire name gets a
# trailing underscore (as Python's pass_). This is a language escape, not a
# rename from the table.
MATLAB_KEYWORDS = frozenset(
    "break case catch classdef continue else elseif end for function global if "
    "otherwise parfor persistent return spmd switch try while".split()
)

# getMapsToken is out of SDK scope for 0.x (BEHAVIOR.md 3).
SKIPPED_OPERATIONS = frozenset({"getMapsToken"})

# The error body is not decoded through this table; ErrorResponse.error is the
# error's `code` (BEHAVIOR.md 3.0, last row).
ERROR_SCHEMA = "ErrorResponse"


class Generator:
    """Walks the OpenAPI components into flat type descriptors."""

    def __init__(self, spec: dict, renames: dict[str, dict[str, str]]) -> None:
        self.schemas = spec["components"]["schemas"]
        self.renames = renames
        self.objects: dict[str, list[tuple[str, str, str]]] = {}
        self.enums: dict[str, list[str]] = {}
        self.used_renames: set[tuple[str, str]] = set()

    # -- helpers ---------------------------------------------------------------

    @staticmethod
    def ref_name(ref: str) -> str:
        return ref.rsplit("/", 1)[-1]

    def deref(self, node: dict) -> tuple[str | None, dict]:
        """Follow one $ref; return (name, schema)."""
        if "$ref" in node:
            name = self.ref_name(node["$ref"])
            return name, self.schemas[name]
        return None, node

    @staticmethod
    def without_null(parts: list[dict]) -> list[dict]:
        return [p for p in parts if p.get("type") != "null"]

    def is_object(self, node: dict) -> bool:
        _, node = self.deref(node)
        if node.get("type") == "object" or "properties" in node:
            return True
        for key in ("allOf", "oneOf", "anyOf"):
            parts = self.without_null(node.get(key, []))
            if parts and all(self.is_object(p) for p in parts):
                return True
        return False

    def collect_properties(self, node: dict) -> tuple[list[tuple[str, dict]], bool]:
        """The merged (name, schema) properties of an object-like node."""
        _, node = self.deref(node)
        props: list[tuple[str, dict]] = []
        seen: set[str] = set()
        is_map = False

        def add(items: list[tuple[str, dict]]) -> None:
            for name, schema in items:
                if name not in seen:
                    seen.add(name)
                    props.append((name, schema))

        for key in ("allOf", "oneOf", "anyOf"):
            for part in self.without_null(node.get(key, [])):
                sub, sub_map = self.collect_properties(part)
                add(sub)
                is_map = is_map or sub_map
        add(list(node.get("properties", {}).items()))
        if not props and isinstance(node.get("additionalProperties"), dict):
            is_map = True
        return props, is_map

    # -- descriptors -------------------------------------------------------------

    def describe(self, node: dict, inline_name: str) -> str:
        """A type descriptor string for ``node`` (see schema.json's header)."""
        ref, target = self.deref(node)
        if ref is not None:
            return self.describe_named(ref, target)
        for key in ("allOf", "oneOf", "anyOf"):
            if key in node:
                parts = self.without_null(node[key])
                nullable = len(parts) < len(node[key])
                if len(parts) == 1:
                    inner = self.describe(parts[0], inline_name)
                elif parts and all(self.is_object(p) for p in parts):
                    inner = self.object(inline_name, node)
                elif parts and all(self.scalar_kind(p) is not None for p in parts):
                    inner = "x"
                else:
                    inner = "x"
                return ("?" + inner) if nullable and not inner.startswith("?") else inner
        types = node.get("type")
        nullable = False
        if isinstance(types, list):
            nullable = "null" in types
            types = [t for t in types if t != "null"]
            types = types[0] if len(types) == 1 else None
        if types == "array":
            items = node.get("items")
            inner = "x" if not items else self.describe(items, inline_name + "[]")
            # An array of raw values stays raw as a whole (GeoJSON coordinates).
            desc = "x" if inner.lstrip("?").replace("a:", "") == "x" else "a:" + inner
        elif types == "object" or "properties" in node:
            if "properties" not in node and isinstance(node.get("additionalProperties"), dict):
                desc = "m"
            elif "properties" not in node:
                desc = "x"
            else:
                desc = self.object(inline_name, node)
        elif "enum" in node and types == "string":
            self.enums.setdefault(inline_name, [str(v) for v in node["enum"]])
            desc = "e:" + inline_name
        else:
            desc = self.scalar_kind(node) or "x"
        return ("?" + desc) if nullable else desc

    @staticmethod
    def scalar_kind(node: dict) -> str | None:
        types = node.get("type")
        if isinstance(types, list):
            types = [t for t in types if t != "null"]
            types = types[0] if len(types) == 1 else None
        if types == "string":
            return "t" if node.get("format") == "date-time" else "s"
        if types in ("number", "integer"):
            return "n"
        if types == "boolean":
            return "b"
        return None

    def describe_named(self, name: str, schema: dict) -> str:
        if self.is_object({"$ref": f"#/components/schemas/{name}"}):
            props, is_map = self.collect_properties(schema)
            if not props and is_map:
                return "m"
            return self.object(name, schema)
        if schema.get("type") == "array" or "items" in schema:
            return self.describe(schema, name)
        if "enum" in schema:
            self.enums.setdefault(name, [str(v) for v in schema["enum"]])
            return "e:" + name
        for key in ("allOf", "oneOf", "anyOf"):
            if key in schema:
                return self.describe(schema, name)
        return self.scalar_kind(schema) or "x"

    def object(self, name: str, node: dict) -> str:
        if name in self.objects:
            return "o:" + name
        self.objects[name] = []  # reserve (recursion)
        props, _ = self.collect_properties(node)
        rows = []
        table = self.renames.get(name, {})
        for wire, schema in props:
            sdk = table.get(wire)
            if sdk is not None:
                self.used_renames.add((name, wire))
            elif wire in MATLAB_KEYWORDS:
                sdk = wire + "_"
            else:
                sdk = wire
            rows.append((wire, sdk, self.describe(schema, f"{name}.{wire}")))
        self.objects[name] = rows
        return "o:" + name


def parse_renames(behavior: str) -> dict[str, dict[str, str]]:
    """The BEHAVIOR.md 3.0 rename table, as {schema: {wire: sdk}}."""
    section = behavior.split("### 3.0", 1)[1].split("### 3.1", 1)[0]
    out: dict[str, dict[str, str]] = {}
    for line in section.splitlines():
        if not line.startswith("| `"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3:
            continue
        schemas = re.findall(r"`([^`]+)`", cells[0])
        wires = re.findall(r"`([^`]+)`", cells[1])
        sdks = re.findall(r"`([^`]+)`", cells[2])
        if len(wires) != len(sdks):
            msg = f"rename row has {len(wires)} wire names and {len(sdks)} SDK names: {line}"
            raise SystemExit(msg)
        for schema in schemas:
            if schema == ERROR_SCHEMA:
                continue
            for wire, sdk in zip(wires, sdks, strict=True):
                out.setdefault(schema, {})[wire] = sdk
    return out


def response_schema(op: dict) -> tuple[dict | None, str | None, object]:
    """The 200 response's schema, media type and example (if any)."""
    content = op.get("responses", {}).get("200", {}).get("content", {})
    for media in ("application/json", "application/geo+json"):
        if media in content:
            body = content[media]
            example = body.get("example")
            if example is None and "examples" in body:
                example = [v.get("value") for v in body["examples"].values()]
            return body.get("schema"), media, example
    return None, None, None


def generate() -> tuple[str, str]:
    spec = yaml.safe_load((SPEC / "openapi" / "v1" / "openapi.yaml").read_text(encoding="utf-8"))
    renames = parse_renames((SPEC / "BEHAVIOR.md").read_text(encoding="utf-8"))
    gen = Generator(spec, renames)
    operations = []
    examples = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method != "get" or op["operationId"] in SKIPPED_OPERATIONS:
                continue
            schema, media, example = response_schema(op)
            if schema is None:
                raise SystemExit(f"{op['operationId']}: no JSON 200 response")
            desc = gen.describe(schema, op["operationId"] + "Response")
            operations.append(
                {
                    "id": op["operationId"],
                    "path": path,
                    "type": desc,
                    "geojson": media == "application/geo+json",
                }
            )
            values = example if isinstance(example, list) else [example]
            for i, value in enumerate(v for v in values if v is not None):
                examples.append(
                    {"name": f"{op['operationId']}#{i}", "type": desc, "body": json.dumps(value)}
                )
    # Component-level examples of object schemas.
    for name, schema in spec["components"]["schemas"].items():
        if name == ERROR_SCHEMA or "example" not in schema:
            continue
        if not gen.is_object({"$ref": f"#/components/schemas/{name}"}):
            continue
        desc = gen.describe_named(name, schema)
        examples.append({"name": name, "type": desc, "body": json.dumps(schema["example"])})

    missing = [
        f"{schema}.{wire}"
        for schema, table in renames.items()
        for wire in table
        if (schema, wire) not in gen.used_renames
    ]
    if missing:
        raise SystemExit("rename rows that match no decoded field: " + ", ".join(missing))

    version = (SPEC / "VERSION").read_text(encoding="utf-8").strip()
    table = {
        "about": (
            "Generated by scripts/gen_schema.py from ensemble-weather-spec "
            f"{version}; do not edit. BSD-2-Clause. Type descriptors: s string, "
            "t date-time, n number, b boolean, m map of strings, x raw, e:Enum, "
            "o:Object, a:<item>, and a leading ? for a nullable value."
        ),
        "spec": version,
        "objects": [
            {
                "name": name,
                "wire": [r[0] for r in rows],
                "sdk": [r[1] for r in rows],
                "type": [r[2] for r in rows],
            }
            for name, rows in sorted(gen.objects.items())
        ],
        "enums": [{"name": n, "values": v} for n, v in sorted(gen.enums.items())],
        "operations": sorted(operations, key=lambda o: o["id"]),
        "renames": [
            {"object": schema, "wire": wire, "sdk": sdk}
            for schema, table_ in sorted(renames.items())
            for wire, sdk in sorted(table_.items())
        ],
    }
    schema_text = json.dumps(table, indent=1, sort_keys=False) + "\n"
    examples_text = json.dumps({"spec": version, "examples": examples}, indent=1) + "\n"
    return schema_text, examples_text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only; change nothing")
    args = parser.parse_args()
    schema_text, examples_text = generate()
    outputs = ((SCHEMA_OUT, schema_text), (EXAMPLES_OUT, examples_text))
    if args.check:
        stale = [
            str(p.relative_to(ROOT))
            for p, text in outputs
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("stale (run scripts/gen_schema.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("generated files match spec/")
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print("wrote " + ", ".join(str(p.relative_to(ROOT)) for p, _ in outputs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
